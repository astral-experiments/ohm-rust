use std::fmt::Write as _;
use std::path::Path;

use super::*;

fn index<T: Eq>(values: &mut Vec<T>, value: T) -> u16 {
    let index = values.iter().position(|old| *old == value).unwrap_or_else(|| {
        values.push(value);
        values.len() - 1
    });
    u16::try_from(index).unwrap()
}

#[test]
fn builtin_target_values() {
    rustc_data_structures::sync::set_dyn_thread_safe_mode(true);
    rustc_span::create_default_session_globals_then(|| {
        let mut strings = Vec::new();
        let mut families = Vec::new();
        let mut targets = String::new();

        for t in Target::builtins() {
            let mut scalars = [None; 8];
            let mut group = Vec::new();
            fields(
                &t,
                |kind, value| scalars[kind] = Some(value),
                |names| {
                    group.extend(names.iter().map(|s| s.to_string()));
                },
            );
            let [abi, arch, endian, env, format, os, width, vendor] =
                scalars.map(|s| index(&mut strings, s.unwrap().as_str().to_owned()));
            let group = group.into_iter().map(|s| index(&mut strings, s)).collect::<Vec<_>>();
            let family = index(&mut families, group);
            let row = [abi, arch, endian, env, family, format, os, width, vendor];
            writeln!(targets, "    {row:?},").unwrap();
        }

        let mut source = String::from(concat!(
            "// @generated by target_cfg_values::tests::builtin_target_values.\n",
            "pub(super) const VALUES: &[&str] = &[\n",
        ));
        for value in strings {
            writeln!(source, "    {value:?},").unwrap();
        }
        source.push_str("];\n\n#[rustfmt::skip]\npub(super) const FAMILIES: &[&[u16]] = &[\n");
        for family in families {
            writeln!(source, "    &{family:?},").unwrap();
        }
        source.push_str("];\n\n#[rustfmt::skip]\npub(super) const TARGETS: &[[u16; 9]] = &[\n");
        source.push_str(&targets);
        source.push_str("];\n");

        if std::env::var_os("RUSTC_BLESS").is_some_and(|value| value != "0") {
            assert!(native_table(), "regenerate on native x86_64 GNU/Linux");
            let path = Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("src/config/builtin_target_cfg_values.rs");
            std::fs::write(path, source).unwrap();
        } else {
            assert_eq!(
                include_str!("../builtin_target_cfg_values.rs"),
                source,
                "run ./x test compiler/rustc_session --bless on native x86_64 GNU/Linux"
            );
        }
    });
}

#[test]
fn builtin_target_values_preserve_family_buckets() {
    use rustc_data_structures::fx::FxHashSet;

    rustc_data_structures::sync::set_dyn_thread_safe_mode(true);
    rustc_span::create_default_session_globals_then(|| {
        let current = Target::builtins().find(|t| t.options.families.is_empty()).unwrap();
        for count in [0, 4] {
            let user: FxHashSet<_> =
                (0..count).map(|n| Some(Symbol::intern(&format!("user-{n}")))).collect();
            let mut expected = user.clone();
            for target in Target::builtins().chain(std::iter::once(current.clone())) {
                expected.extend(target.options.families.iter().map(|s| Some(Symbol::intern(s))));
            }
            let mut actual = std::array::from_fn(|_| ExpectedValues::Any);
            actual[4] = ExpectedValues::Some(user);
            fill(actual.each_mut(), &current);
            let ExpectedValues::Some(values) = &actual[4] else { unreachable!() };
            assert_eq!(values.capacity(), expected.capacity());
            // A compiler driver can observe the order of the public set.
            #[allow(rustc::potential_query_instability)]
            let same_order = values.iter().eq(expected.iter());
            assert!(same_order);
        }
    });
}
